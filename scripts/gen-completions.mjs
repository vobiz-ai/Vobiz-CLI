#!/usr/bin/env node
// Generates static shell completions from the built command tree (dist/cli.js):
//   completions/vobiz.bash  completions/_vobiz (zsh)  completions/vobiz.fish  completions/vobiz.ps1
// Usage: npm run build && npm run completions:gen
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { flatten, loadCommandTree, root } from "./lib/command-tree.mjs";

const HEADER = "GENERATED by scripts/gen-completions.mjs from the Vobiz CLI command tree. Do not edit; run `npm run completions:gen`.";
const SAFE = /^[\w.:@+-]+$/;

const tree = await loadCommandTree();
const nodes = flatten(tree);
const rootOptions = tree.options;

/** One row per command path, with root (global) options merged in, since commander accepts them anywhere. */
const rows = nodes.map((n) => {
  const options = [...n.options];
  for (const o of rootOptions) if (!options.some((x) => x.long === o.long)) options.push(o);
  return {
    key: n.path.join(" "),
    children: n.children.filter((c) => SAFE.test(c.name)).flatMap((c) => [{ name: c.name, desc: c.description }, ...c.aliases.filter((a) => SAFE.test(a)).map((a) => ({ name: a, desc: c.description }))]),
    options: options.flatMap((o) => [o.long, o.short].filter(Boolean).filter((f) => SAFE.test(f)).map((flag) => ({ flag, desc: o.description, takesValue: o.takesValue, choices: (o.choices ?? []).filter((c) => SAFE.test(c)) }))),
  };
});

const oneLine = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const sq = (s) => `'${oneLine(s).replace(/'/g, `'\\''`)}'`; // POSIX shells
const psq = (s) => `'${oneLine(s).replace(/'/g, "''")}'`; // PowerShell
const fishq = (s) => `'${oneLine(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const outDir = join(root, "completions");
mkdirSync(outDir, { recursive: true });

// ---------- bash (3.2 compatible: no associative arrays) ----------
{
  const caseOf = (fn) => rows.map((r) => `    ${sq(r.key)}) echo ${sq(fn(r))} ;;`).join("\n");
  const choiceCases = rows.flatMap((r) => r.options.filter((o) => o.choices.length).map((o) => `    ${sq(`${r.key}|${o.flag}`)}) echo ${sq(o.choices.join(" "))} ;;`)).join("\n");
  const bash = `# bash completion for vobiz. ${HEADER}
# Install: vobiz completion bash > ~/.local/share/bash-completion/completions/vobiz

_vobiz_children() {
  case "$1" in
${caseOf((r) => r.children.map((c) => c.name).join(" "))}
  esac
}

_vobiz_options() {
  case "$1" in
${caseOf((r) => r.options.map((o) => o.flag).join(" "))}
  esac
}

_vobiz_value_options() {
  case "$1" in
${caseOf((r) => r.options.filter((o) => o.takesValue).map((o) => o.flag).join(" "))}
  esac
}

_vobiz_choices() {
  case "$1|$2" in
${choiceCases || "    *) ;;"}
  esac
}

_vobiz() {
  local cur prev cmdpath word i skip choices
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  cmdpath=""
  skip=0
  for ((i = 1; i < COMP_CWORD; i++)); do
    word="\${COMP_WORDS[i]}"
    if [ "$skip" = 1 ]; then skip=0; continue; fi
    case "$word" in
      --*=*) continue ;;
      -*)
        case " $(_vobiz_value_options "$cmdpath") " in *" $word "*) skip=1 ;; esac
        continue
        ;;
    esac
    case " $(_vobiz_children "$cmdpath") " in
      *" $word "*) cmdpath="\${cmdpath:+$cmdpath }$word" ;;
    esac
  done

  case " $(_vobiz_value_options "$cmdpath") " in
    *" $prev "*)
      choices="$(_vobiz_choices "$cmdpath" "$prev")"
      if [ -n "$choices" ]; then
        COMPREPLY=($(compgen -W "$choices" -- "$cur"))
      else
        COMPREPLY=($(compgen -f -- "$cur"))
      fi
      return 0
      ;;
  esac

  if [[ "$cur" == -* ]]; then
    COMPREPLY=($(compgen -W "$(_vobiz_options "$cmdpath")" -- "$cur"))
  else
    COMPREPLY=($(compgen -W "$(_vobiz_children "$cmdpath")" -- "$cur"))
  fi
  return 0
}

complete -o default -F _vobiz vobiz
`;
  writeFileSync(join(outDir, "vobiz.bash"), bash);
}

// ---------- zsh ----------
{
  const zdesc = (name, desc) => sq(`${name.replace(/:/g, "\\:")}:${oneLine(desc)}`);
  const caseOf = (fn) => rows.map((r) => `    ${sq(r.key)}) reply=(${fn(r)}) ;;`).join("\n");
  const choiceCases = rows.flatMap((r) => r.options.filter((o) => o.choices.length).map((o) => `    ${sq(`${r.key}|${o.flag}`)}) reply=(${o.choices.map(sq).join(" ")}) ;;`)).join("\n");
  const zsh = `#compdef vobiz
# zsh completion for vobiz. ${HEADER}
# Install: vobiz completion zsh > "\${fpath[1]}/_vobiz"  (then restart the shell)

_vobiz_children() {
  reply=()
  case "$1" in
${caseOf((r) => r.children.map((c) => zdesc(c.name, c.desc)).join(" "))}
  esac
}

_vobiz_options() {
  reply=()
  case "$1" in
${caseOf((r) => r.options.map((o) => zdesc(o.flag, o.desc)).join(" "))}
  esac
}

_vobiz_value_options() {
  reply=()
  case "$1" in
${caseOf((r) => r.options.filter((o) => o.takesValue).map((o) => sq(o.flag)).join(" "))}
  esac
}

_vobiz_choices() {
  reply=()
  case "$1|$2" in
${choiceCases || "    *) ;;"}
  esac
}

_vobiz() {
  local cmdpath="" word skip=0 i
  local -a names cands values
  for (( i = 2; i < CURRENT; i++ )); do
    word="\${words[i]}"
    if (( skip )); then skip=0; continue; fi
    case "$word" in
      --*=*) continue ;;
      -*)
        _vobiz_value_options "$cmdpath"
        (( \${reply[(Ie)$word]} )) && skip=1
        continue
        ;;
    esac
    _vobiz_children "$cmdpath"
    names=("\${(@)reply%%:*}")
    (( \${names[(Ie)$word]} )) && cmdpath="\${cmdpath:+$cmdpath }$word"
  done

  local prev="\${words[CURRENT-1]}"
  _vobiz_value_options "$cmdpath"
  if (( \${reply[(Ie)$prev]} )); then
    _vobiz_choices "$cmdpath" "$prev"
    if (( \${#reply} )); then
      values=("\${reply[@]}")
      compadd -a values
    else
      _files
    fi
    return
  fi

  if [[ "$PREFIX" == -* ]]; then
    _vobiz_options "$cmdpath"
    cands=("\${reply[@]}")
    _describe -t options 'option' cands
  else
    _vobiz_children "$cmdpath"
    cands=("\${reply[@]}")
    if (( \${#cands} )); then
      _describe -t commands 'command' cands
    else
      _files
    fi
  fi
}

if [[ "\${funcstack[1]}" == "_vobiz" ]]; then
  _vobiz "$@"
else
  compdef _vobiz vobiz
fi
`;
  writeFileSync(join(outDir, "_vobiz"), zsh);
}

// ---------- fish ----------
{
  const switchOf = (fn) => rows.map((r) => `        case ${fishq(r.key)}\n            printf '%s\\n' ${fn(r) || "''"}`).join("\n");
  const lines = [
    `# fish completion for vobiz. ${HEADER}`,
    "# Install: vobiz completion fish > ~/.config/fish/completions/vobiz.fish",
    "",
    "function __vobiz_children",
    "    switch $argv[1]",
    switchOf((r) => r.children.map((c) => fishq(c.name)).join(" ")),
    "    end",
    "end",
    "",
    "function __vobiz_value_options",
    "    switch $argv[1]",
    switchOf((r) => r.options.filter((o) => o.takesValue).map((o) => fishq(o.flag)).join(" ")),
    "    end",
    "end",
    "",
    "function __vobiz_cmdpath",
    "    set -l tokens (commandline -opc)",
    "    set -l p ''",
    "    set -l skip 0",
    "    for t in $tokens[2..-1]",
    "        if test $skip = 1",
    "            set skip 0",
    "            continue",
    "        end",
    "        switch $t",
    "            case '--*=*'",
    "                continue",
    "            case '-*'",
    "                if contains -- $t (__vobiz_value_options \"$p\")",
    "                    set skip 1",
    "                end",
    "                continue",
    "        end",
    "        if contains -- $t (__vobiz_children \"$p\")",
    "            set p (string trim -- \"$p $t\")",
    "        end",
    "    end",
    "    echo $p",
    "end",
    "",
    "function __vobiz_at",
    "    test (__vobiz_cmdpath) = \"$argv[1]\"",
    "end",
    "",
    "complete -c vobiz -f",
  ];
  const rootRow = rows.find((r) => r.key === "");
  const globalFlags = new Set(rootRow.options.map((o) => o.flag));
  const optLine = (cond, o) => {
    const flag = o.flag.startsWith("--") ? `-l ${o.flag.slice(2)}` : `-s ${o.flag.slice(1)}`;
    const value = o.takesValue ? (o.choices.length ? ` -x -a ${fishq(o.choices.join(" "))}` : " -r -F") : "";
    return `complete -c vobiz${cond} ${flag}${value} -d ${fishq(o.desc)}`;
  };
  for (const o of rootRow.options) lines.push(optLine("", o));
  for (const r of rows) {
    const cond = ` -n ${fishq(`__vobiz_at "${r.key}"`)}`;
    for (const c of r.children) lines.push(`complete -c vobiz${cond} -a ${fishq(c.name)} -d ${fishq(c.desc)}`);
    for (const o of r.options) if (!globalFlags.has(o.flag)) lines.push(optLine(cond, o));
  }
  writeFileSync(join(outDir, "vobiz.fish"), lines.join("\n") + "\n");
}

// ---------- PowerShell ----------
{
  const pair = (a, b) => `@(${psq(a)}, ${psq(oneLine(b) || a)})`;
  const entries = rows.map((r) => {
    const choices = r.options.filter((o) => o.choices.length).map((o) => `${psq(o.flag)} = @(${o.choices.map(psq).join(", ")})`);
    return [
      `    ${psq(r.key)} = @{`,
      `        c = @(${r.children.map((c) => pair(c.name, c.desc)).join(", ")})`,
      `        o = @(${r.options.map((o) => pair(o.flag, o.desc)).join(", ")})`,
      `        v = @(${r.options.filter((o) => o.takesValue).map((o) => psq(o.flag)).join(", ")})`,
      `        x = @{ ${choices.join("; ")} }`,
      "    }",
    ].join("\n");
  });
  const ps = `# PowerShell completion for vobiz. ${HEADER}
# Install: vobiz completion powershell | Out-String | Invoke-Expression   (add it to $PROFILE to keep it)

$global:VobizCompletionTree = @{
${entries.join("\n")}
}

Register-ArgumentCompleter -Native -CommandName 'vobiz', 'vobiz.exe' -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $tree = $global:VobizCompletionTree
    $tokens = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $tokens.Count -gt 0) {
        $tokens = if ($tokens.Count -gt 1) { $tokens[0..($tokens.Count - 2)] } else { @() }
    }
    $cmdpath = ''
    $skip = $false
    foreach ($t in $tokens) {
        if ($skip) { $skip = $false; continue }
        if ($t -like '--*=*') { continue }
        if ($t -like '-*') {
            if ($tree[$cmdpath].v -contains $t) { $skip = $true }
            continue
        }
        $names = @($tree[$cmdpath].c | ForEach-Object { $_[0] })
        if ($names -contains $t) { $cmdpath = if ($cmdpath) { "$cmdpath $t" } else { $t } }
    }
    $node = $tree[$cmdpath]
    $prev = if ($tokens.Count -gt 0) { $tokens[-1] } else { '' }
    if ($node.v -contains $prev) {
        $choices = $node.x[$prev]
        if ($choices) {
            $choices | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
                [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
            }
        }
        return
    }
    $candidates = if ($wordToComplete -like '-*') { $node.o } else { $node.c }
    $candidates | Where-Object { $_[0] -like "$wordToComplete*" } | ForEach-Object {
        $kind = if ($_[0] -like '-*') { 'ParameterName' } else { 'Command' }
        [System.Management.Automation.CompletionResult]::new($_[0], $_[0], $kind, $_[1])
    }
}
`;
  // UTF-8 with a BOM: Windows PowerShell 5.1 reads a BOM-less script in the ANSI code page, which garbles the
  // non-ASCII descriptions (and can turn a UTF-8 byte into a quote character). PowerShell 7 accepts either.
  writeFileSync(join(outDir, "vobiz.ps1"), "\uFEFF" + ps);
}

process.stderr.write(`wrote completions for ${nodes.length} commands to completions/\n`);
