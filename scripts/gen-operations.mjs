#!/usr/bin/env node
// Generates src/generated/operations.ts from the vendored OpenAPI documents in spec/.
// The CLI never guesses paths or fields: every command resolves its HTTP operation here by operationId,
// and `vobiz api --list` and the docs are produced from the same table. Run `npm run spec:sync` to refresh spec/.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  { api: "voice", file: "spec/openapi-voice.yaml" },
  { api: "sms", file: "spec/openapi-sms.yaml" },
];

function deref(doc, node, seen = new Set()) {
  if (!node || typeof node !== "object") return node;
  if (node.$ref) {
    if (seen.has(node.$ref)) return {};
    seen.add(node.$ref);
    const parts = node.$ref.replace(/^#\//, "").split("/");
    let cur = doc;
    for (const p of parts) cur = cur?.[p.replace(/~1/g, "/").replace(/~0/g, "~")];
    return deref(doc, cur, seen);
  }
  return node;
}

function schemaType(s) {
  if (!s) return "string";
  if (Array.isArray(s.type)) return s.type.find((t) => t !== "null") ?? "string";
  if (s.type) return s.type;
  if (s.enum) return typeof s.enum[0];
  if (s.properties) return "object";
  if (s.items) return "array";
  if (s.oneOf || s.anyOf) return "string";
  return "string";
}

function params(doc, list, where) {
  return (list ?? [])
    .map((p) => deref(doc, p))
    .filter((p) => p.in === where)
    .map((p) => {
      const s = deref(doc, p.schema ?? {});
      return {
        name: p.name,
        required: !!p.required,
        type: schemaType(s),
        description: (p.description ?? s.description ?? "").trim(),
        enum: s.enum ?? undefined,
        default: s.default,
        deprecated: p.deprecated || s.deprecated ? true : undefined,
      };
    });
}

function bodyOf(doc, op) {
  const rb = deref(doc, op.requestBody);
  if (!rb) return { required: false, contentType: undefined, props: [] };
  const [contentType, media] = Object.entries(rb.content ?? {})[0] ?? [];
  let schema = deref(doc, media?.schema ?? {});
  if (schema.allOf) {
    const merged = { properties: {}, required: [] };
    for (const part of schema.allOf) {
      const d = deref(doc, part);
      Object.assign(merged.properties, d.properties ?? {});
      merged.required.push(...(d.required ?? []));
    }
    schema = merged;
  }
  const required = new Set(schema.required ?? []);
  const props = Object.entries(schema.properties ?? {}).map(([name, raw]) => {
    const s = deref(doc, raw);
    return {
      name,
      required: required.has(name),
      type: schemaType(s),
      description: (s.description ?? "").trim(),
      enum: s.enum ?? undefined,
      default: s.default,
      items: s.items ? schemaType(deref(doc, s.items)) : undefined,
      deprecated: s.deprecated ? true : undefined,
    };
  });
  return { required: !!rb.required, contentType, props };
}

const ops = [];
for (const src of sources) {
  const doc = YAML.parse(readFileSync(join(root, src.file), "utf8"));
  const baseUrl = doc.servers?.[0]?.url ?? "";
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const op = item[method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${src.file}: ${method.toUpperCase()} ${path} has no operationId`);
      const all = [...(item.parameters ?? []), ...(op.parameters ?? [])];
      ops.push({
        id: op.operationId,
        api: src.api,
        baseUrl,
        method: method.toUpperCase(),
        path,
        tag: op.tags?.[0] ?? "Other",
        summary: (op.summary ?? "").trim(),
        description: (op.description ?? "").trim().split("\n")[0],
        deprecated: !!op.deprecated,
        pathParams: params(doc, all, "path"),
        queryParams: params(doc, all, "query"),
        body: bodyOf(doc, op),
      });
    }
  }
}

const dupes = ops.map((o) => `${o.api}:${o.id}`).filter((k, i, a) => a.indexOf(k) !== i);
if (dupes.length) throw new Error(`duplicate operationIds: ${dupes.join(", ")}`);

const header = `// GENERATED by scripts/gen-operations.mjs from spec/*.yaml. Do not edit; run \`npm run gen\`.
export type Api = "voice" | "sms";
export type HttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
export interface Param { name: string; required: boolean; type: string; description: string; enum?: (string | number)[]; default?: unknown; items?: string; deprecated?: boolean }
export interface Operation {
  id: string; api: Api; baseUrl: string; method: HttpMethod; path: string; tag: string; summary: string; description: string; deprecated: boolean;
  pathParams: Param[]; queryParams: Param[]; body: { required: boolean; contentType?: string; props: Param[] };
}
export const OPERATIONS: readonly Operation[] = `;
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/operations.ts"),
  header + JSON.stringify(ops, null, 2) + ` as const;\n\nexport const SPEC_OPERATION_COUNT = ${ops.length};\n`,
);
console.log(`generated ${ops.length} operations (${ops.filter((o) => o.api === "voice").length} voice, ${ops.filter((o) => o.api === "sms").length} sms)`);
