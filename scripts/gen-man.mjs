#!/usr/bin/env node
// Generates the man page man/vobiz.1 (roff) from the built command tree (dist/cli.js).
// Usage: npm run build && npm run man:gen      Preview: man ./man/vobiz.1
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EXIT_CODES, flatten, loadCommandTree, readVersion, root, usageLine } from "./lib/command-tree.mjs";

const tree = await loadCommandTree();
const version = await readVersion();

// roff escaping: backslashes, leading dots/quotes, and hyphens in flags.
const esc = (s) => String(s ?? "").replace(/\s+/g, " ").trim().replace(/\\/g, "\\e").replace(/-/g, "\\-").replace(/^([.'])/, "\\&$1");

const out = [];
out.push(
  `.\\" GENERATED by scripts/gen-man.mjs from the Vobiz CLI command tree. Do not edit; run \`npm run man:gen\`.`,
  `.TH VOBIZ 1 "" "vobiz ${esc(version)}" "Vobiz CLI"`,
  ".SH NAME",
  "vobiz \\- the official command\\-line interface for Vobiz",
  ".SH SYNOPSIS",
  ".B vobiz",
  "[\\fIglobal options\\fR] \\fIcommand\\fR [\\fIsubcommand\\fR] [\\fIarguments\\fR] [\\fIoptions\\fR]",
  ".SH DESCRIPTION",
  esc(tree.description || "Manage your Vobiz account from a terminal or CI: voice calls, conferences, recordings, call records, phone numbers, SIP trunks, applications, endpoints, sub-accounts, messaging, VobizXML and the Vobiz agent tools."),
  ".PP",
  "Run \\fBvobiz login\\fR once to save an Auth ID and Auth Token, or set \\fBVOBIZ_AUTH_ID\\fR and \\fBVOBIZ_AUTH_TOKEN\\fR.",
  "Data goes to standard output; progress, hints and warnings go to standard error.",
  "Commands that spend money, contact people or change the account ask for confirmation; pass \\fB\\-\\-yes\\fR in scripts.",
);

const optionBlock = (options) => {
  for (const o of options) {
    out.push(".TP", `.B ${esc(o.flags)}`, esc(o.description) + (o.choices?.length ? ` (one of: ${esc(o.choices.join(", "))})` : ""));
  }
};

out.push(".SH GLOBAL OPTIONS");
optionBlock(tree.options);

out.push(".SH COMMANDS");
for (const node of flatten(tree).slice(1)) {
  out.push(`.SS ${esc(["vobiz", ...node.path].join(" "))}`);
  if (node.description) out.push(esc(node.description));
  out.push(".PP", `.B ${esc(usageLine(node))}`);
  if (node.aliases.length) out.push(".PP", `Aliases: ${esc(node.aliases.join(", "))}`);
  for (const a of node.args) out.push(".TP", `.I ${esc(a.name)}`, esc(a.description || (a.required ? "Required." : "Optional.")));
  const own = node.options.filter((o) => !tree.options.some((g) => g.long === o.long) && o.long !== "--help");
  if (own.length) {
    out.push(".PP", "Options:");
    optionBlock(own);
  }
}

out.push(
  ".SH ENVIRONMENT",
  ...[
    ["VOBIZ_AUTH_ID, VOBIZ_AUTH_TOKEN", "Credentials for one invocation (CI). Flags win over the environment, which wins over the saved profile."],
    ["VOBIZ_PROFILE", "The saved profile to use."],
    ["VOBIZ_OUTPUT", "Default output format: table, json, yaml, tsv or plain."],
    ["VOBIZ_YES", "Skip confirmation prompts, like --yes."],
    ["VOBIZ_BASE_URL, VOBIZ_SMS_BASE_URL", "Gateway overrides."],
    ["VOBIZ_TIMEOUT", "Per-request timeout in seconds."],
    ["VOBIZ_CONFIG_DIR", "Configuration directory (default: $XDG_CONFIG_HOME/vobiz or ~/.config/vobiz)."],
    ["VOBIZ_NO_UPDATE_CHECK", "Disable the daily version check (also disabled when CI is set)."],
    ["NO_COLOR, FORCE_COLOR", "Standard color handling."],
  ].flatMap(([k, v]) => [".TP", `.B ${esc(k)}`, esc(v)]),
  ".SH EXIT STATUS",
  ...EXIT_CODES.flatMap(([code, text]) => [".TP", `.B ${code}`, esc(text)]),
  ".SH FILES",
  ".TP",
  ".I ~/.config/vobiz/credentials.json",
  "Saved profiles (mode 0600).",
  ".TP",
  ".I ~/.config/vobiz/config.json",
  "Settings (non\\-secret).",
  ".SH SEE ALSO",
  "https://www.vobiz.ai/docs/resources/cli",
  ".SH BUGS",
  "Report issues at https://github.com/vobiz\\-ai/Vobiz\\-CLI/issues.",
);

mkdirSync(join(root, "man"), { recursive: true });
writeFileSync(join(root, "man", "vobiz.1"), out.join("\n") + "\n");
process.stderr.write("wrote man/vobiz.1\n");
